const details = new Map();
function screen() {
  const pathname = typeof window === 'undefined' ? '/' : window.location.pathname;
  const base = routeScreen(pathname, routes);
  const detail = [...details.values()].reverse().find(value => value.base === base);
  return detail ? base + '/' + detail.tab : base;
}
function storage(name) { try { return typeof window === 'undefined' ? undefined : window[name]; } catch { return undefined; } }
export const readRecorder = createReadRecorder({ app: 'wala', screen, storage: storage('localStorage'), sessionStorage: storage('sessionStorage'), fetcher: typeof window === 'undefined' ? undefined : (...args) => window.fetch(...args) });
export function registerReadScreen(base, tab) {
  // Call with static UI values, never labels entered by users.
  const key = Symbol(); details.set(key, { base, tab });
  return () => details.delete(key);
}
export function configureReadTelemetry(options) { readRecorder.configure(options); }
if (typeof window !== 'undefined') {
  window.__firestoreReads = { status: readRecorder.status, snapshot: readRecorder.snapshot, flush: readRecorder.flush, verifyConnection: () => readRecorder.verifyConnection() };
  window.addEventListener('pagehide', () => { readRecorder.checkpoint(); void readRecorder.flush(); });
  document.addEventListener('visibilitychange', () => { if (document.visibilityState === 'hidden') { readRecorder.checkpoint(); void readRecorder.flush(); } });
}
